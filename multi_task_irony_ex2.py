import os
import json
import random
import numpy as np
import pandas as pd
import torch

from sklearn.metrics import accuracy_score, precision_recall_fscore_support

from datasets import Dataset

from transformers import (
    RobertaTokenizer,
    RobertaForSequenceClassification,
    Trainer,
    TrainingArguments
)



PROJECT_DIR = "/content/drive/MyDrive/implicit_hate_project"

DATASET_JSON = os.path.join(PROJECT_DIR, "dataset.json")
SPLITS_JSON = os.path.join(PROJECT_DIR, "post_id_divisions.json")

OUTPUT_DIR = os.path.join(PROJECT_DIR, "roberta_baseline")

os.makedirs(OUTPUT_DIR, exist_ok=True)



SEED = 42

random.seed(SEED)
np.random.seed(SEED)
torch.manual_seed(SEED)
torch.cuda.manual_seed_all(SEED)



with open(DATASET_JSON) as f:
    dataset = json.load(f)

with open(SPLITS_JSON) as f:
    splits = json.load(f)



label_map = {
    "normal":0,
    "offensive":1,
    "hatespeech":2
}

def majority_vote(labels):

    counts = {}

    for l in labels:
        counts[l] = counts.get(l,0)+1

    m = max(counts.values())

    winners = [k for k,v in counts.items() if v==m]

    if len(winners)>1:
        return None

    return winners[0]



rows=[]

for split_name in ["train","val","test"]:

    for pid in splits[split_name]:

        post = dataset[pid]

        labels = [a["label"] for a in post["annotators"]]

        majority = majority_vote(labels)

        if majority is None:
            continue

        text = " ".join(post["post_tokens"])

        rows.append({

            "text":text,
            "label":label_map[majority],
            "split":split_name
        })

df = pd.DataFrame(rows)

print(df.head())

print(df.groupby("split").size())



train_df = df[df.split=="train"][["text","label"]]
val_df = df[df.split=="val"][["text","label"]]
test_df = df[df.split=="test"][["text","label"]]

train_ds = Dataset.from_pandas(train_df)
val_ds = Dataset.from_pandas(val_df)
test_ds = Dataset.from_pandas(test_df)


tokenizer = RobertaTokenizer.from_pretrained("roberta-base")

def tokenize(batch):

    return tokenizer(
        batch["text"],
        truncation=True,
        padding="max_length",
        max_length=128
    )

train_ds = train_ds.map(tokenize, batched=True)
val_ds = val_ds.map(tokenize, batched=True)
test_ds = test_ds.map(tokenize, batched=True)

columns = [
    "input_ids",
    "attention_mask",
    "label"
]

train_ds.set_format(type="torch", columns=columns)
val_ds.set_format(type="torch", columns=columns)
test_ds.set_format(type="torch", columns=columns)



model = RobertaForSequenceClassification.from_pretrained(
    "roberta-base",
    num_labels=3
)



def compute_metrics(eval_pred):

    logits, labels = eval_pred

    preds = np.argmax(logits, axis=1)

    precision, recall, f1, _ = precision_recall_fscore_support(
        labels,
        preds,
        average="macro"
    )

    acc = accuracy_score(labels,preds)

    return {
        "accuracy":acc,
        "macro_precision":precision,
        "macro_recall":recall,
        "macro_f1":f1
    }



training_args = TrainingArguments(
    output_dir=OUTPUT_DIR,

    eval_strategy="epoch",
    save_strategy="epoch",
    logging_strategy="epoch",

    learning_rate=2e-5,
    per_device_train_batch_size=16,
    per_device_eval_batch_size=16,

    num_train_epochs=5,

    weight_decay=0.01,

    load_best_model_at_end=True,
    metric_for_best_model="macro_f1",
    greater_is_better=True,

    save_total_limit=1,
    seed=42,
)


trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_ds,
    eval_dataset=val_ds,
    compute_metrics=compute_metrics
)



trainer.train()



results = trainer.evaluate(test_ds)

print(results)


trainer.save_model(OUTPUT_DIR)
tokenizer.save_pretrained(OUTPUT_DIR)

print("Finished.")

