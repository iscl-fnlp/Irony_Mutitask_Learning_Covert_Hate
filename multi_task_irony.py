import torch
import torch.nn as nn
from transformers import RobertaModel

class MultiTaskRoberta(nn.Module):
    def __init__(self, num_ihc_labels=6, num_irony_labels=2, dropout_prob=0.1):
        super(MultiTaskRoberta, self).__init__()


        self.roberta = RobertaModel.from_pretrained('roberta-base')


        self.dropout = nn.Dropout(dropout_prob)


        self.ihc_classifier = nn.Linear(self.roberta.config.hidden_size, num_ihc_labels)


        self.irony_classifier = nn.Linear(self.roberta.config.hidden_size, num_irony_labels)

    def forward(self, input_ids, attention_mask, task='ihc'):

        outputs = self.roberta(input_ids=input_ids, attention_mask=attention_mask)


        pooled_output = outputs.last_hidden_state[:, 0, :]
        x = self.dropout(pooled_output)


        if task == 'ihc':
            logits = self.ihc_classifier(x)
        elif task == 'irony':
            logits = self.irony_classifier(x)
        else:
            raise ValueError(f"Unknown task: {task}")

        return logits


