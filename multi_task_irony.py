class RobustEvalDataset(Dataset):
    def __init__(self, df, tokenizer, max_len=128):
        # Auto-detect text column
        possible_text_cols = ["post", "text", "tweet", "sentence"]
        text_col = next((col for col in possible_text_cols if col in df.columns), None)

        if text_col is None:
            raise KeyError(f"No text column found in DataFrame. Available columns: {list(df.columns)}")

        self.posts = df[text_col].astype(str).tolist()

        # Ensure labels are mapped to integer IDs
        raw_labels = df["category"].tolist() if "category" in df.columns else df["label"].tolist()
        self.labels = [label2id[l] if isinstance(l, str) else int(l) for l in raw_labels]

        self.tokenizer = tokenizer
        self.max_len = max_len

    def __len__(self):
        return len(self.posts)

    def __getitem__(self, idx):
        text = self.posts[idx]
        label = self.labels[idx]

        encoding = self.tokenizer(
            text,
            truncation=True,
            padding="max_length",
            max_length=self.max_len,
            return_tensors="pt"
        )

        return {
            "input_ids": encoding["input_ids"].flatten(),
            "attention_mask": encoding["attention_mask"].flatten(),
            "label": torch.tensor(label, dtype=torch.long)
        }


