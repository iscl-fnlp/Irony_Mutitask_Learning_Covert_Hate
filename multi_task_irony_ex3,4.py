def train_one_epoch(

    model,

    hate_loader,

    irony_loader,

    optimizer,

    scheduler

):

    model.train()

    running_loss = 0

    irony_iterator = iter(irony_loader)

    for hate_batch in hate_loader:

        try:

            irony_batch = next(irony_iterator)

        except StopIteration:

            irony_iterator = iter(irony_loader)

            irony_batch = next(irony_iterator)

        optimizer.zero_grad()



        hate_ids = hate_batch["input_ids"].to(device)

        hate_mask = hate_batch["attention_mask"].to(device)

        hate_labels = hate_batch["label"].to(device)

        hate_logits = model(

            input_ids=hate_ids,

            attention_mask=hate_mask,

            task="hate"

        )

        hate_loss = hate_loss_fn(

            hate_logits,

            hate_labels

        )



        irony_ids = irony_batch["input_ids"].to(device)

        irony_mask = irony_batch["attention_mask"].to(device)

        irony_labels = irony_batch["label"].to(device)

        irony_logits = model(

            input_ids=irony_ids,

            attention_mask=irony_mask,

            task="irony"

        )

        irony_loss = irony_loss_fn(

            irony_logits,

            irony_labels

        )



        total_loss = (

            ALPHA * hate_loss

            +

            (1 - ALPHA) * irony_loss

        )

        total_loss.backward()

        torch.nn.utils.clip_grad_norm_(

            model.parameters(),

            1.0

        )

        optimizer.step()

        scheduler.step()

        running_loss += total_loss.item()

    return running_loss / len(hate_loader)



