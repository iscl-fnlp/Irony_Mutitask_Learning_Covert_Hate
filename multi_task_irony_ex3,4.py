class MultiTaskRoberta(nn.Module):

    def __init__(self):

        super().__init__()



        self.roberta = RobertaModel.from_pretrained(
            "roberta-base"
        )

        hidden_size = self.roberta.config.hidden_size

        self.dropout = nn.Dropout(0.1)



        self.hate_classifier = nn.Linear(
            hidden_size,
            3
        )


        self.irony_classifier = nn.Linear(
            hidden_size,
            2
        )

    def forward(
        self,
        input_ids,
        attention_mask,
        task="hate"
    ):

        outputs = self.roberta(
            input_ids=input_ids,
            attention_mask=attention_mask
        )

        cls = outputs.last_hidden_state[:, 0]

        cls = self.dropout(cls)

        if task == "hate":

            logits = self.hate_classifier(cls)

        elif task == "irony":

            logits = self.irony_classifier(cls)

        else:

            raise ValueError("Task must be 'hate' or 'irony'.")

        return logits

